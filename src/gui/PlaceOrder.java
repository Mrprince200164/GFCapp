    private void loadproducts() {

        try {

            ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `category_item`");

            Vector<String> vector = new Vector<>();
            vector.add("Select");

            while (resultSet.next()) {
                vector.add(resultSet.getString("name"));
                OrderProductMap.put(resultSet.getString("name"), resultSet.getString("id"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(vector);
            jComboBox1.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadOrders() {
        try {

            ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `order`"                   
                    + "INNER JOIN `product` ON `order`.`product_id` = `product`.`id`"
                    + "INNER JOIN `district` ON `order`.`district_id` = `district`.`id`"
                    + "INNER JOIN `category` ON `product`.`category_id` = `category`.`id`"
                    + "INNER JOIN `category_item` ON `product`.`category_item_id` = `category_item`.`id`"
                    + "INNER JOIN `customer` ON `order`.`customer_mobile` = `customer`.`mobile` WHERE `mobile`='" + mobile + "'");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("category_item.name"));
                vector.add(resultSet.getString("weight"));
                vector.add(resultSet.getString("district.name"));
                vector.add(resultSet.getString("date"));


                model.addRow(vector);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

    }

    private void loadcustomers() {

        try {
            ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `customer`"
                    + "INNER JOIN `district` ON `customer`.`district_id` = `district`.`id` WHERE `email` ='" + email + "'");

            if (resultSet.next()) {

                customerMobile.setText(resultSet.getString("mobile"));
                customerDistrict.setText(resultSet.getString("district.name"));
                mobile = String.valueOf(resultSet.getString("mobile"));
                district = String.valueOf(resultSet.getString("district_id"));

            }

        } catch (Exception e) {
        }

    }
    
        private String genarateId() {

        String orderId = "";

        try {

            ResultSet resultSet = MySQL2.executeSearch("SELECT MAX(`id`) AS id FROM `order`");

            if (resultSet.next()) {

                String oid = resultSet.getString("id");

                if (oid != null) {
                     
                    int count = Integer.parseInt(oid.replace("Ord-", ""));
                    orderId = String.format("Ord-%03d", count + 1);
                    jLabel7.setText(orderId);

                } else {
                    orderId = "Ord-001";
                    jLabel7.setText(orderId);
                }

            }

        } catch (Exception e){ 
            e.printStackTrace();
        }
        return orderId;

    }

