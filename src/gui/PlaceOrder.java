    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {

            String productName = String.valueOf(jComboBox1.getSelectedItem());
            String weight = jTextField4.getText();
            String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());

            if (productName.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select a Product", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (weight.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `order` WHERE `customer_mobile`= '" + mobile + "' AND `product_id` = '" + OrderProductMap.get(productName) + "'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "This user already ordered items", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {
                    
                    String id = genarateId();
                    
                    MySQL2.executeIUD("INSERT INTO `order`(`id`,`product_id`,`weight`,`customer_mobile`,`district_id`,`date`)"
                            + "VALUES('" + id + "','" + OrderProductMap.get(productName) + "','" + weight + "','" + mobile + "','" + district + "','" + date + "')");
                    

                    loadOrders();
                    reset();

                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

