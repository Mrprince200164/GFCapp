    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String line1 = jTextField1.getText();
            String line2 = jTextField2.getText();
            String district = String.valueOf(jComboBox1.getSelectedItem());

            if (line1.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter address line 1", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (line2.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter address line 2", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (district.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select a District", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                boolean isFound = false;

                for (int i = 0; i < jTable3.getRowCount(); i++) {

                    String getLine1 = String.valueOf(jTable3.getValueAt(i, 1));
                    String getLine2 = String.valueOf(jTable3.getValueAt(i, 2));
                    String getDistrict = String.valueOf(jTable3.getValueAt(i, 3));

                    if (getLine1.equals(line1) && getLine2.equals(line2) && getDistrict.equals(district)) {
                        JOptionPane.showMessageDialog(this, "Address already added", "Warning", JOptionPane.WARNING_MESSAGE);
                        isFound = true;
                        break;
                    }
                }

                if (!isFound) {
                    MySQL2.executeIUD("INSERT INTO `supplier_address`(`line_01`,`line_02`,`district_id`,`supplier_email`)"
                            + "VALUES('" + line1 + "','" + line2 + "','" + districtMap.get(district) + "','" + this.email + "')");

                    loadAddress();
                    reset();
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

