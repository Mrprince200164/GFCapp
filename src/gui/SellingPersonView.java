    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        System.out.println(cuemail);
        
       loadcustomer();
       
       

        String email = jLabel12.getText();
        String msg = jTextArea1.getText();

        String subject = "Contact with Supplier";
        String body = String.format("First Name: %s\nLast Name: %s\nMobile: %s\nDistrict: %s\nMassage: %s",
                                    Cfname, Clname, Cmobile, Cdistrict, msg);

        try {
            // Create the mailto URI
            URI mailto = new URI("mailto:" + email +
                    "?subject=" + encodeURIComponent(subject) +
                    "&body=" + encodeURIComponent(body));

            // Open the default email client
            if (Desktop.isDesktopSupported() && Desktop.getDesktop().isSupported(Desktop.Action.MAIL)) {
                Desktop.getDesktop().mail(mailto);
            } else {
                JOptionPane.showMessageDialog(this, "Desktop mail not supported.");
            }
        } catch (URISyntaxException | IOException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error opening email client.");
        }
    


    }//GEN-LAST:event_jButton1ActionPerformed

