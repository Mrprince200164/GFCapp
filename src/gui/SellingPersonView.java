        private String encodeURIComponent(String value) {
        try {
            return java.net.URLEncoder.encode(value, "UTF-8").replace("+", "%20");
        } catch (Exception ex) {
            ex.printStackTrace();
            return value;
        }
    }
        
    private void loadsupplier() {

        try {

            ResultSet resultSet = MySQL2.executeSearch("SELECT * FROM `supplier`"
                    + "INNER JOIN `district` ON `supplier`.`district_id` = `district`.`id` WHERE `email`='" + semail + "'");

            if (resultSet.next()) {

                jLabel7.setText(resultSet.getString("first_name"));
                jLabel8.setText(resultSet.getString("last_name"));
                jLabel9.setText(resultSet.getString("mobile"));
                jLabel10.setText(resultSet.getString("district.name"));

            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }  
    
